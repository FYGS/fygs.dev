// Builds the React bundle the playground's React previews load, from the React that is installed in node_modules, and
// records its Subresource Integrity hash. The preview used to load React 18 from unpkg.com (a moving version, no
// integrity check, a third party able to run code in the learner's preview): it now loads this file from the site.
//
//   node scripts/build-sandbox-vendor.mjs
//
// Writes public/sandbox/vendor/react.js and app/_lib/sandbox-vendor.generated.ts (run it again after upgrading React;
// tests/unit/sandbox/vendor-bundle.test.ts fails when the two disagree).
import { createHash } from "node:crypto";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const require = createRequire(path.join(root, "package.json"));
const esbuild = require("esbuild");

const reactVersion = require("react/package.json").version;
const reactDomVersion = require("react-dom/package.json").version;
if (reactVersion !== reactDomVersion) throw new Error(`react ${reactVersion} and react-dom ${reactDomVersion} differ`);

const entry = `
import * as React from "react";
import * as ReactDOM from "react-dom";
import * as ReactDOMClient from "react-dom/client";
// The globals the previews expect (the UMD builds of React 18 set the same two names)
window.React = React;
window.ReactDOM = Object.assign({}, ReactDOM, ReactDOMClient);
`;

const result = await esbuild.build({
  stdin: { contents: entry, resolveDir: root, sourcefile: "sandbox-react-entry.js" },
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  legalComments: "none",
  define: { "process.env.NODE_ENV": '"production"' },
  write: false,
});

const code = `/* React ${reactVersion} + ReactDOM (production), bundled by scripts/build-sandbox-vendor.mjs */\n${result.outputFiles[0].text}`;
const outDir = path.join(root, "public/sandbox/vendor");
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "react.js"), code, "utf8");

const integrity = `sha384-${createHash("sha384").update(code, "utf8").digest("base64")}`;
fs.writeFileSync(
  path.join(root, "app/_lib/sandbox-vendor.generated.ts"),
  `// Generated by scripts/build-sandbox-vendor.mjs: do not edit.
// The React bundle of the playground previews (public/sandbox/vendor/react.js) and its integrity hash.
export const SANDBOX_REACT = {
  version: ${JSON.stringify(reactVersion)},
  path: "/sandbox/vendor/react.js",
  integrity: ${JSON.stringify(integrity)},
} as const;
`,
  "utf8",
);

console.log(`react ${reactVersion}: ${(code.length / 1024).toFixed(0)} kB, ${integrity}`);
